#!/usr/bin/env python3
"""
docs_index.py — generate a repository's documentation index from the documents.

The index is the table in `docs/README.md` that names every document in the
repository and says in one line what it covers. It is derived, not written:
each row comes from the document's own summary line, so a description lives in
exactly one place (the document) and the index can never drift from it. This
is the fleet documentation framework's UPS-DOC-02/03 (bamr87/bamr87
specs/DOCS.md).

A document's summary is, in order of preference:
  1. its front-matter `description:`, when the file has front matter;
  2. the `>` blockquote directly under its H1 (GitHub alerts excluded);
  3. otherwise the first sentence of its first paragraph — a fallback that
     `--lint` reports, because a sentence lifted from the body is rarely a
     good description.

What is listed:
  - root documents of record (every root *.md except README.md, CLAUDE.md
    and Jekyll pages, i.e. files whose front matter sets `layout:` or
    `permalink:`);
  - every *.md under each doc root (default `docs/`). A subdirectory that has
    its own README.md or index.md is listed as that one file and not entered:
    a nested index owns its directory.

The generated span sits between these markers in the index file; prose above
or below it is the repository's own. Options ride on the start marker, so the
configuration lives beside the output it shapes:

  <!-- AUTO:docs-index:start roots=docs,specs exclude=docs/media/ root=yes -->
  <!-- AUTO:docs-index:end -->

  roots=   comma-separated doc roots (default: docs)
  exclude= comma-separated path prefixes or globs to leave out
  root=    yes|no — list the root documents of record (default: yes)

Usage:
  docs_index.py --write [--root PATH]   rewrite the span (creates docs/README.md
                                        with the markers when it does not exist)
  docs_index.py --check [--root PATH]   exit 1 when the span is stale or absent
  docs_index.py --lint  [--root PATH]   list documents with no H1, several H1s,
                                        or no summary line; exit 1 if any
  docs_index.py --json  [--root PATH]   print the collected documents

Stdlib only (Python 3.8+). Vendored byte-identical from the bamr87 hub
(tools/docs_index.py) into each repository's tools/; change it there first.
"""
# Vendored verbatim from the bamr87 hub; it opts out of the host repo's
# linters rather than chase every project's configuration.
# ruff: noqa
# flake8: noqa
# mypy: ignore-errors
import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys

INDEX = "docs/README.md"
START_RE = re.compile(r"^<!-- AUTO:docs-index:start(?P<opts>[^>]*?)-->[ \t]*$", re.M)
END = "<!-- AUTO:docs-index:end -->"
NOTE = ("<!-- Generated by tools/docs_index.py from each document's summary line "
        "(front-matter `description:` or the `>` line under its H1). Edit the "
        "documents, then run `python3 tools/docs_index.py --write`. -->")
SUMMARY_MAX = 240

# Root documents whose wording is the fleet's, not the repository's: release
# tooling or a kit owns them, so a fallback description is better than asking
# anyone to hand-edit them. A summary line in the file still wins.
WELL_KNOWN = {
    "AGENTS.md": "How to work in this repository — commands, layout, conventions; canonical for agents and contributors.",
    "CONTRIBUTING.md": "How to contribute: branches, commits, local gates and pull requests.",
    "CHANGELOG.md": "Release history: the notable changes in each version, newest first.",
    "SECURITY.md": "Supported versions and how to report a vulnerability privately.",
    "CODE_OF_CONDUCT.md": "The standards of behaviour for everyone taking part.",
    "SCHEMA.md": "Where everything lives and where a new file goes (the Pyramid Schema root, linted by tools/schema_lint.py).",
    "PRD.md": "The product requirements: problem, users, goals, scope and success measures.",
    "ATTRIBUTION.md": "Third-party work this repository includes, and its licenses.",
}
ROOT_ORDER = ["AGENTS.md", "CONTRIBUTING.md", "CHANGELOG.md", "SECURITY.md",
              "CODE_OF_CONDUCT.md", "SCHEMA.md", "PRD.md"]
ROOT_SKIP = {"README.md", "CLAUDE.md"}

FENCE_RE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")
H1_RE = re.compile(r"^#[ \t]+(.+?)[ \t]*#*[ \t]*$")
SETEXT_H1_RE = re.compile(r"^=+[ \t]*$")


# --- files --------------------------------------------------------------------

def list_files(root):
    """Tracked and new (not ignored) files, so a fresh doc shows up before its commit."""
    try:
        out = subprocess.run(
            ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
            cwd=root, capture_output=True, text=True, check=True).stdout
        files = sorted({p for p in out.splitlines() if p})
        return [p for p in files if os.path.isfile(os.path.join(root, p))]
    except (OSError, subprocess.CalledProcessError):
        found = []
        for base, dirs, names in os.walk(root):
            dirs[:] = [d for d in dirs if not d.startswith(".") and d != "node_modules"]
            for n in names:
                found.append(os.path.relpath(os.path.join(base, n), root).replace(os.sep, "/"))
        return sorted(found)


def read(root, path):
    try:
        with open(os.path.join(root, path), encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return ""


# --- parsing ------------------------------------------------------------------

def split_front_matter(text):
    """Return (front-matter dict of top-level scalars, body)."""
    if not text.startswith("---"):
        return {}, text
    lines = text.splitlines()
    if lines[0].strip() != "---":
        return {}, text
    for i in range(1, len(lines)):
        if lines[i].strip() in ("---", "..."):
            return parse_scalars(lines[1:i]), "\n".join(lines[i + 1:])
    return {}, text


def parse_scalars(lines):
    """Top-level `key: value` pairs, with `>`/`|` block scalars folded to one line."""
    data, i = {}, 0
    while i < len(lines):
        m = re.match(r"^([A-Za-z_][\w-]*):[ \t]*(.*)$", lines[i])
        i += 1
        if not m:
            continue
        key, value = m.group(1), m.group(2).strip()
        if value[:1] in (">", "|"):
            block = []
            while i < len(lines) and (not lines[i].strip() or lines[i][:1] in (" ", "\t")):
                block.append(lines[i].strip())
                i += 1
            value = " ".join(b for b in block if b)
        elif len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        data[key] = value
    return data


def outside_fences(body):
    """Yield (index, line) for lines that are not inside fenced code."""
    fence = None
    for i, line in enumerate(body.splitlines()):
        m = FENCE_RE.match(line)
        if m:
            mark = m.group(1)
            if fence is None:
                fence = mark[0] * len(mark)
            elif mark[0] == fence[0] and len(mark) >= len(fence):
                fence = None
            continue
        if fence is None:
            yield i, line


def first_sentence(text):
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text).strip()


def balanced(text):
    return (text.count("[") == text.count("]") and text.count("(") == text.count(")")
            and text.count("`") % 2 == 0)


def clean(text):
    text = re.sub(r"<!--.*?-->", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) > SUMMARY_MAX:
        cut = text[:SUMMARY_MAX].rsplit(" ", 1)[0]
        # Never cut through a link or a code span: back off to before it.
        while cut and not balanced(cut):
            at = max(cut.rfind("["), cut.rfind("`"), cut.rfind("("))
            cut = cut[:at].rstrip() if at > 0 else ""
        text = cut.rstrip(",;:—- ") + "…"
    return text.replace("|", "\\|")


LINK_RE = re.compile(r"(\]\()([^)\s]+)(\))")


def rebase(summary, doc_path, index):
    """Rewrite the summary's relative links from the document's folder to the index's."""
    doc_dir, index_dir = os.path.dirname(doc_path), os.path.dirname(index)

    def fix(m):
        target = m.group(2)
        if re.match(r"^([a-z][a-z0-9+.-]*:|/|<)", target, re.I):
            return m.group(0)
        path, _, anchor = target.partition("#")
        resolved = os.path.normpath(os.path.join(doc_dir, path)) if path else doc_path
        new = os.path.relpath(resolved, index_dir or ".").replace(os.sep, "/")
        return m.group(1) + new + ("#" + anchor if anchor else "") + m.group(3)

    return LINK_RE.sub(fix, summary)


def describe(text):
    """Return (title, summary, source, h1_count) for one Markdown document."""
    meta, body = split_front_matter(text)
    lines = body.splitlines()
    visible = list(outside_fences(body))
    h1s = [(i, H1_RE.match(line).group(1)) for i, line in visible if H1_RE.match(line)]
    for i, line in visible:
        if SETEXT_H1_RE.match(line) and i > 0 and lines[i - 1].strip() and not lines[i - 1].startswith(("#", ">", "|", "-", "*")):
            h1s.append((i - 1, lines[i - 1].strip()))
    h1s.sort()
    title = meta.get("title") or (h1s[0][1] if h1s else "")
    if meta.get("description"):
        return title, clean(meta["description"]), "front-matter", len(h1s)

    start = h1s[0][0] + 1 if h1s else 0
    if h1s and SETEXT_H1_RE.match(lines[start] if start < len(lines) else ""):
        start += 1
    visible_from = [(i, line) for i, line in visible if i >= start]
    # The blockquote directly under the H1 is the summary (alerts are not).
    for i, line in visible_from:
        s = line.strip()
        if not s or s.startswith("<!--"):
            continue
        if s.startswith(">") and h1s and not re.match(r"^>\s*\[!", s):
            quote = []
            for _, q in [(j, l) for j, l in visible_from if j >= i]:
                q = q.strip()
                if not q.startswith(">") or not q.lstrip("> ").strip():
                    break
                quote.append(q.lstrip(">").strip())
            return title, clean(" ".join(quote)), "blockquote", len(h1s)
        break
    # Fallback: the first sentence of the first prose paragraph.
    para = []
    for i, line in visible_from:
        s = line.strip()
        if not s:
            if para:
                break
            continue
        if s.startswith(("#", "|", "<", "![", "---", "***", "{%", "{{")) or re.match(r"^[-*+]\s|^\d+[.)]\s|^>", s):
            if para:
                break
            continue
        para.append(s)
    summary = first_sentence(" ".join(para)) if para else ""
    return title, clean(summary), "fallback" if summary else "none", len(h1s)


# --- collection ---------------------------------------------------------------

def parse_options(marker_opts):
    opts = {"roots": ["docs"], "exclude": [], "root": True}
    for key, value in re.findall(r"(\w+)=(\"[^\"]*\"|\S+)", marker_opts or ""):
        value = value.strip('"')
        if key == "roots":
            opts["roots"] = [r.strip().strip("/") for r in value.split(",") if r.strip()]
        elif key == "exclude":
            opts["exclude"] = [e.strip() for e in value.split(",") if e.strip()]
        elif key == "root":
            opts["root"] = value.lower() not in ("no", "false", "0", "off")
    return opts


def excluded(path, patterns):
    for p in patterns:
        if path.startswith(p) or fnmatch.fnmatch(path, p):
            return True
    return False


def is_site_page(text):
    meta, _ = split_front_matter(text)
    return "layout" in meta or "permalink" in meta


def collect(root, opts, index=INDEX, files=None, reader=None):
    """Every document the index lists, as dicts grouped by section.

    `files` (repository-relative paths) and `reader(path) -> text` default to
    the working tree; a caller holding a blob-less clone passes its own.
    """
    files = list_files(root) if files is None else sorted(files)
    reader = reader or (lambda path: read(root, path))
    md = [p for p in files if p.lower().endswith(".md") and not excluded(p, opts["exclude"])]
    docs = []

    if opts["root"]:
        for path in [p for p in md if "/" not in p and p not in ROOT_SKIP and p != index]:
            text = reader(path) or ""
            if is_site_page(text):
                continue
            title, summary, source, h1 = describe(text)
            if source in ("fallback", "none") and path in WELL_KNOWN:
                summary, source = WELL_KNOWN[path], "well-known"
            docs.append(dict(path=path, group="", title=title, summary=rebase(summary, path, index),
                             source=source, h1=h1))

    index_dir = os.path.dirname(index)
    for droot in opts["roots"]:
        prefix = droot + "/"
        own = next((prefix + n for n in ("README.md", "index.md") if (prefix + n) in files), None)
        if own and own != index and droot != index_dir:
            # A root below the index's folder that has its own index is one row.
            parent = droot.rsplit("/", 1)[0] + "/" if "/" in droot else ""
            title, summary, source, h1 = describe(reader(own) or "")
            docs.append(dict(path=own, group=parent, title=title, summary=rebase(summary, own, index),
                             source=source, h1=h1, directory=prefix))
            continue
        for p in [p for p in md if p.startswith(prefix) and p != index]:
            parts = p[len(prefix):].split("/")
            owner, group = None, prefix + "".join(d + "/" for d in parts[:-1])
            # The shallowest subdirectory with its own index owns everything below it.
            for depth in range(1, len(parts)):
                sub = prefix + "".join(d + "/" for d in parts[:depth])
                own = next((sub + n for n in ("README.md", "index.md") if (sub + n) in files), None)
                if own:
                    owner, group = (sub, prefix + "".join(d + "/" for d in parts[:depth - 1])) if p == own else ("skip", "")
                    break
            if owner == "skip":
                continue
            title, summary, source, h1 = describe(reader(p) or "")
            docs.append(dict(path=p, group=group, title=title, summary=rebase(summary, p, index),
                             source=source, h1=h1, directory=owner))
    return docs


def root_key(doc):
    name = doc["path"]
    return (ROOT_ORDER.index(name) if name in ROOT_ORDER else len(ROOT_ORDER), name.lower())


def render(docs, index=INDEX, opts_text=""):
    base = os.path.dirname(index)

    def link(doc):
        shown = doc.get("directory") or doc["path"]
        href = os.path.relpath(doc["path"], base or ".").replace(os.sep, "/")
        return "[`%s`](%s)" % (shown, href)

    def table(rows):
        out = ["| Document | What it covers |", "| --- | --- |"]
        out += ["| %s | %s |" % (link(d), d["summary"] or "—") for d in rows]
        return out

    lines = ["<!-- AUTO:docs-index:start%s-->" % opts_text, NOTE, ""]
    groups = {}
    for d in docs:
        groups.setdefault(d["group"], []).append(d)
    if "" in groups:
        lines += ["### Repository root", ""] + table(sorted(groups.pop(""), key=root_key)) + [""]
    for group in sorted(groups, key=lambda g: (g.count("/"), g.lower())):
        rows = sorted(groups[group], key=lambda d: (bool(d.get("directory")), d["path"].lower()))
        lines += ["### `%s`" % group, ""] + table(rows) + [""]
    lines.append(END)
    return "\n".join(lines)


# --- the index file -----------------------------------------------------------

def locate(text):
    """(start, end, opts_text) of the span in the index text, or None."""
    m = START_RE.search(text)
    if not m:
        return None
    end = text.find(END, m.end())
    if end < 0:
        return None
    return m.start(), end + len(END), m.group("opts")


def repo_name(root):
    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"], cwd=root,
                             capture_output=True, text=True, check=True).stdout.strip()
        name = url.rstrip("/").rsplit("/", 1)[-1]
        return name[:-4] if name.endswith(".git") else name
    except (OSError, subprocess.CalledProcessError):
        return os.path.basename(os.path.abspath(root))


def build(root, index=INDEX, files=None, reader=None):
    """Return (current text or None, regenerated text); `files`/`reader` as in collect()."""
    if reader is None:
        current = read(root, index) if os.path.isfile(os.path.join(root, index)) else None
    else:
        current = reader(index) if files is None or index in files else None
    if current is None:
        opts = parse_options("")
        span = render(collect(root, opts, index, files, reader), index, " ")
        fresh = "# %s documentation\n\n> Every document in this repository, one line each.\n\n%s\n" % (repo_name(root), span)
        return None, fresh
    where = locate(current)
    if where is None:
        return current, None
    start, end, opts_text = where
    opts = parse_options(opts_text)
    span = render(collect(root, opts, index, files, reader), index, opts_text)
    return current, current[:start] + span + current[end:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--lint", action="store_true")
    mode.add_argument("--json", action="store_true")
    ap.add_argument("--root", default=".", help="repository root (default: .)")
    ap.add_argument("--index", default=INDEX, help="index file (default: docs/README.md)")
    args = ap.parse_args(argv)
    root = args.root

    if args.json or args.lint:
        current = read(root, args.index)
        where = locate(current) if current else None
        opts = parse_options(where[2] if where else "")
        docs = collect(root, opts, args.index)
        if args.json:
            print(json.dumps(docs, indent=2, ensure_ascii=False))
            return 0
        problems = []
        for d in docs:
            if d["source"] == "well-known":
                continue
            if d["h1"] == 0 and not d["title"]:
                problems.append("%s: no H1" % d["path"])
            elif d["h1"] > 1:
                problems.append("%s: %d H1 headings (one per document)" % (d["path"], d["h1"]))
            if d["source"] in ("fallback", "none"):
                problems.append("%s: no summary line (add `> one sentence` under the H1, "
                                "or `description:` to its front matter)" % d["path"])
        for p in problems:
            print(p)
        return 1 if problems else 0

    current, fresh = build(root, args.index)
    if fresh is None:
        print("%s has no `<!-- AUTO:docs-index:start -->` … `%s` span; add the two "
              "marker lines where the index belongs, then re-run." % (args.index, END), file=sys.stderr)
        return 1
    if args.check:
        if current != fresh:
            print("%s is stale: run `python3 tools/docs_index.py --write`" % args.index, file=sys.stderr)
            return 1
        return 0
    if current != fresh:
        path = os.path.join(root, args.index)
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(fresh)
        print("wrote %s" % args.index)
    return 0


if __name__ == "__main__":
    sys.exit(main())
