#!/usr/bin/env python3
"""Bundle the ASCII Motion files into the scripts the players load.

Every piece of art the terminal surfaces draw is an ASCII Motion file
(https://github.com/cameronfoxly/Ascii-Motion) — usually a `.asciimtn` session,
the format the editor opens — never a string in code. This script embeds them:

    termforge/motion/*.asciimtn   -> termforge/core/art.js
        framework defaults (banner, cow, sl) for any TermForge app; vendored
        into the web bundle with the rest of termforge/core/
    src/help/data/motion.yaml art -> web/assets/js/art-clips.js
        the game's art: banner, encounter portraits, room vignettes, ...
    src/help/data/motion.yaml clips -> web/assets/js/fx-clips.js
        the command-stage animations + manifest (aliases, stage set, events)

Usage:
    python3 scripts/build_motion.py            # write all bundles
    python3 scripts/build_motion.py --check    # fail if any bundle is stale

`render()` and `check()` are importable (tests, validate_static_web.py).
Needs pyyaml (as export_static_web.py does).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "src" / "help" / "data" / "motion.yaml"
CORE_ART_DIR = ROOT / "termforge" / "motion"
CORE_ART_OUT = ROOT / "termforge" / "core" / "art.js"
GAME_ART_OUT = ROOT / "web" / "assets" / "js" / "art-clips.js"
CLIPS_OUT = ROOT / "web" / "assets" / "js" / "fx-clips.js"
SUFFIXES = (".asciimtn", ".json", ".txt")
FIX_IT = "run 'make web-build' and commit the result"

# Editor UI state a session file carries that playback never reads.
_SESSION_UI_KEYS = ("tools", "ui", "palettes", "characterPalettes", "typography")
_COMPACT = {"ensure_ascii": False, "separators": (",", ":"), "sort_keys": False}


def load_registry() -> dict[str, Any]:
    data = yaml.safe_load(REGISTRY.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError(f"{REGISTRY} must contain a top-level YAML object")
    return data


def load_source(path: Path) -> Any:
    """One ASCII Motion file as TermForge's parse() takes it.

    JSON exports and sessions stay objects (editor UI state dropped); text
    exports stay strings.
    """
    raw = path.read_text(encoding="utf-8").lstrip("﻿")
    if not raw.strip().startswith(("{", "[")):
        return raw
    data = json.loads(raw)
    if isinstance(data, dict):
        for key in _SESSION_UI_KEYS:
            data.pop(key, None)
        meta = data.get("metadata")
        if isinstance(meta, dict):
            meta.pop("userAgent", None)
    return data


def _dump(value: Any) -> str:
    return json.dumps(value, **_COMPACT)


def core_art() -> dict[str, Any]:
    return {
        path.stem: load_source(path)
        for path in sorted(CORE_ART_DIR.iterdir())
        if path.suffix in SUFFIXES
    }


def game_art(registry: dict[str, Any]) -> dict[str, Any]:
    return {
        name: load_source(ROOT / entry["file"])
        for name, entry in (registry.get("art") or {}).items()
    }


def stage_clips(registry: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    clips: dict[str, Any] = {}
    meta: dict[str, Any] = {}
    aliases: dict[str, str] = {}
    stage: list[str] = []
    for name, entry in (registry.get("clips") or {}).items():
        clips[name] = load_source(ROOT / entry["file"])
        meta[name] = {
            "title": entry.get("title", name),
            "description": entry.get("description", ""),
            "file": entry["file"],
        }
        on_stage = entry.get("stage", True)
        if on_stage:
            stage.append(name)
        for alias in entry.get("aliases") or []:
            aliases[alias] = name
            if on_stage:
                stage.append(alias)
    manifest = {
        "clips": meta,
        "aliases": aliases,
        "stage": stage,
        "events": [
            {"event": item["event"], "motion": item["motion"]}
            for item in registry.get("events") or []
        ],
    }
    return clips, manifest


def _core_art_js(art: dict[str, Any]) -> str:
    return (
        "// Generated by scripts/build_motion.py from termforge/motion/*.asciimtn\n"
        "// (make web-build). Do not edit: open the .asciimtn in ASCII Motion instead.\n"
        "(function (global, factory) {\n"
        '    "use strict";\n'
        '    const hasCjs = typeof module !== "undefined" && module.exports;\n'
        "    const api = factory();\n"
        "    if (hasCjs) {\n"
        "        module.exports = api;\n"
        "    } else {\n"
        "        global.TermForge = global.TermForge || {};\n"
        "        global.TermForge.art = api;\n"
        "    }\n"
        '})(typeof globalThis !== "undefined" ? globalThis : this, function () {\n'
        '    "use strict";\n'
        "    // The framework's neutral default art, as ASCII Motion sources. Apps\n"
        "    // add or override names through the Shell's `art` option.\n"
        f"    const DEFAULT_ART = Object.freeze({_dump(art)});\n"
        "    return { DEFAULT_ART };\n"
        "});\n"
    )


def _classic_js(registry_note: str, assignments: list[tuple[str, Any]]) -> str:
    body = "".join(f"    global.{name} = {_dump(value)};\n" for name, value in assignments)
    return (
        f"// Generated by scripts/build_motion.py from {registry_note} (make web-build)."
        " Do not edit.\n"
        "(function (global) {\n"
        '    "use strict";\n'
        f"{body}"
        '})(typeof globalThis !== "undefined" ? globalThis : this);\n'
    )


def render() -> dict[Path, str]:
    """Every bundle this script owns, path -> exact file text."""
    registry = load_registry()
    clips, manifest = stage_clips(registry)
    return {
        CORE_ART_OUT: _core_art_js(core_art()),
        GAME_ART_OUT: _classic_js(
            "src/help/data/motion.yaml (art)", [("BashcrawlArtClips", game_art(registry))]
        ),
        CLIPS_OUT: _classic_js(
            "src/help/data/motion.yaml (clips)",
            [("BashcrawlFxClips", clips), ("BashcrawlFxClipManifest", manifest)],
        ),
    }


def check() -> list[str]:
    errors = []
    for path, text in render().items():
        rel = path.relative_to(ROOT).as_posix()
        if not path.is_file():
            errors.append(f"motion bundle missing: {rel} — {FIX_IT}")
        elif path.read_text(encoding="utf-8") != text:
            errors.append(f"motion bundle stale: {rel} — {FIX_IT}")
    return errors


def main() -> int:
    if "--check" in sys.argv[1:]:
        errors = check()
        for err in errors:
            print(f"ERROR: {err}", file=sys.stderr)
        if not errors:
            print("motion bundles fresh")
        return 1 if errors else 0
    for path, text in render().items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"  bundled   {path.relative_to(ROOT).as_posix()}")
    print("motion bundles up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
