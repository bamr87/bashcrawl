#!/usr/bin/env python3
"""Generate docs/generated/ from the sources that already hold the facts.

The content registries (src/help/data/*.yaml), the course frontmatter
(courses/<id>/course.md), the Makefile's ``##`` target comments and the
launcher's own ``bashcrawl help`` text are the single sources
of truth; these pages are projections of them, so they are written here and
never by hand (fleet docs framework UPS-DOC-05).

  python3 scripts/generate_contract_docs.py           rewrite every page
  python3 scripts/generate_contract_docs.py --check   exit 1 if a page is stale

``make generate-contract-docs`` runs the first; ``make validate-contracts``
runs the second.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import course_loader  # noqa: E402  (sibling script, pyyaml only)

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "src/help/data"
OUT_DIR = ROOT / "docs/generated"
REGEN = "make generate-contract-docs"
BANNER = (
    f"<!-- GENERATED by `{REGEN}` (scripts/generate_contract_docs.py) — do not edit by hand -->"
)


def _head(title: str, summary: str) -> list[str]:
    """The GENERATED banner, the one H1 and the summary line every page opens with."""
    return [BANNER, "", f"# {title}", "", f"> {summary}", ""]


def _load_yaml(name: str) -> dict[str, Any]:
    path = DATA_DIR / name
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError(f"{name} must contain a top-level object")
    return data


def _render_rooms(data: dict[str, Any]) -> str:
    rooms = data.get("rooms", {})
    lines = _head(
        "Rooms Index",
        "Every room in the dungeon with its title, path, whether it starts hidden"
        " and its context hint, from `src/help/data/rooms.yaml`.",
    )
    for key, spec in sorted(rooms.items()):
        if not isinstance(spec, dict):
            continue
        title = spec.get("title", key)
        path = spec.get("path", "")
        hint = spec.get("context_hint", "")
        lines.append(f"## {key}")
        lines.append(f"- Title: {title}")
        lines.append(f"- Path: `{path}`")
        lines.append(f"- Hidden: `{bool(spec.get('hidden', False))}`")
        if hint:
            lines.append(f"- Hint: {hint}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _render_quests(data: dict[str, Any]) -> str:
    quests = data.get("quests", [])
    lines = _head(
        "Quest Index",
        "Every quest with its objective, XP and the command and location that"
        " complete it, from `src/help/data/quests.yaml`.",
    )
    for quest in quests:
        if not isinstance(quest, dict):
            continue
        qid = quest.get("id", "?")
        lines.append(f"## Quest {qid}: {quest.get('title', '')}")
        lines.append(f"- Objective: {quest.get('objective', '')}")
        lines.append(f"- XP: `{quest.get('xp', 0)}`")
        completion = quest.get("completion", {}) or {}
        if isinstance(completion, dict):
            lines.append(f"- Completion command: `{completion.get('command', '')}`")
            lines.append(f"- Completion location: `{completion.get('location', '')}`")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _render_runtime_commands(data: dict[str, Any]) -> str:
    commands = data.get("commands", [])
    lines = _head(
        "Runtime Commands",
        "Every command the runtimes know and which of them (Python, bash, AI,"
        " the web demo) implements it, from `src/help/data/runtime_commands.yaml`.",
    ) + [
        "| Command | Python | Bash | AI | Demo |",
        "|---|---:|---:|---:|---:|",
    ]
    for cmd in commands:
        if not isinstance(cmd, dict):
            continue
        runtimes = cmd.get("runtimes", {}) or {}
        lines.append(
            "| {name} | {python} | {bash} | {ai} | {demo} |".format(
                name=cmd.get("name", ""),
                python="yes" if runtimes.get("python") else "no",
                bash="yes" if runtimes.get("bash") else "no",
                ai="yes" if runtimes.get("ai") else "no",
                demo="yes" if runtimes.get("demo") else "no",
            )
        )
    return "\n".join(lines).rstrip() + "\n"


def _render_motion(data: dict[str, Any]) -> str:
    lines = _head(
        "Motion Clips and Art",
        "Every ASCII Motion stage clip and piece of art the game draws, the events"
        " that trigger them and the framework defaults, from `src/help/data/motion.yaml`.",
    ) + [
        # One line per paragraph: the markdown-oneline workflow unwraps prose.
        "Every file below is an"
        " [ASCII Motion](https://github.com/cameronfoxly/Ascii-Motion) `.asciimtn`"
        " session: open it at <https://ascii-motion.app>, edit, export a session,"
        " and replace the file. Workflow:"
        " [docs/termforge/ascii-motion.md](../termforge/ascii-motion.md).",
        "",
        "## Stage clips",
        "",
        "| Motion | Title | Aliases | File | Plays on |",
        "|---|---|---|---|---|",
    ]
    for name, entry in (data.get("clips") or {}).items():
        aliases = ", ".join(f"`{a}`" for a in entry.get("aliases") or []) or "—"
        lines.append(
            f"| `{name}` | {entry.get('title', '')} | {aliases} | `{entry.get('file', '')}` "
            f"| {entry.get('description', '')} |"
        )
    lines += ["", "Game events that replace the command's motion (first match wins):", ""]
    for rule in data.get("events") or []:
        lines.append(f"- `{rule.get('event')}` → `{rule.get('motion')}`")
    lines += [
        "",
        "## Art",
        "",
        "Static one-frame clips drawn with `Shell#art(name)`.",
        "",
        "| Name | Title | File | Used for |",
        "|---|---|---|---|",
    ]
    for name, entry in (data.get("art") or {}).items():
        lines.append(
            f"| `{name}` | {entry.get('title', '')} | `{entry.get('file', '')}` "
            f"| {entry.get('description', '')} |"
        )
    core = sorted(p.stem for p in (ROOT / "termforge/motion").glob("*.asciimtn"))
    lines += [
        "",
        "Framework defaults (`termforge/motion/`, bundled into `termforge/core/art.js`;"
        " an app's `art` option overrides them by name): "
        + ", ".join(f"`{name}`" for name in core)
        + ".",
    ]
    return "\n".join(lines).rstrip() + "\n"


MAKE_TARGET_RE = re.compile(r"^([a-zA-Z_-]+):[^=]*?## (.+)$")


def _render_make_targets() -> str:
    """Every documented target, read from the same ``##`` comments ``make help`` prints."""
    lines = _head(
        "Make Targets",
        "Every `make` target and what it does, read from the `##` comments in the"
        " `Makefile` (the same text `make help` prints).",
    ) + ["| Target | What it does |", "|---|---|"]
    for line in (ROOT / "Makefile").read_text(encoding="utf-8").splitlines():
        m = MAKE_TARGET_RE.match(line)
        if m:
            desc = m.group(2).strip().replace("|", "\\|")
            lines.append(f"| `make {m.group(1)}` | {desc} |")
    return "\n".join(lines).rstrip() + "\n"


def _render_launcher() -> str:
    """The launcher's subcommands, exactly as ``bin/bashcrawl help`` prints them."""
    usage = subprocess.run(
        ["bash", str(ROOT / "bin/bashcrawl"), "help"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.rstrip()
    lines = _head(
        "Launcher Commands",
        "Every `bin/bashcrawl` subcommand and what it needs, exactly as"
        " `bin/bashcrawl help` prints it.",
    ) + ["```text", usage, "```"]
    return "\n".join(lines).rstrip() + "\n"


def _render_courses() -> str:
    """The course catalogue, from each courses/<id>/course.md and its lessons."""
    courses = course_loader.build_bundle(ROOT)["courses"]
    lines = _head(
        "Course Catalogue",
        "Every course on the learning platform in play order, with its level, lessons,"
        " prerequisites and the commands it teaches, from `courses/<id>/course.md`.",
    ) + [
        "Start one in any surface with `learn ID`; copy its lab into real bash with"
        " `bin/bashcrawl lab ID`. Writing a course:"
        " [authoring-courses.md](../authoring-courses.md).",
        "",
        "| ID | Course | Level | Lessons | Requires | Summary |",
        "|---|---|---|---:|---|---|",
    ]
    for c in courses:
        requires = ", ".join(f"`{r}`" for r in c["requires"]) or "—"
        summary = c["summary"].replace("|", "\\|")
        lines.append(
            f"| `{c['id']}` | {c['title']} | {c['level']} | {len(c['lessons'])} "
            f"| {requires} | {summary} |"
        )
    return "\n".join(lines).rstrip() + "\n"


PAGES = {
    "courses.md": "Course Catalogue",
    "launcher.md": "Launcher Commands",
    "make-targets.md": "Make Targets",
    "motion.md": "Motion Clips and Art",
    "quests.md": "Quest Index",
    "rooms.md": "Rooms Index",
    "runtime-commands.md": "Runtime Commands",
}


def _render_index() -> str:
    lines = _head(
        "Generated reference",
        "Reference pages generated from the content registries, the courses, the"
        f" `Makefile` and the launcher; rebuild them with `{REGEN}` instead of editing them.",
    )
    lines += [f"- [{title}]({name})" for name, title in PAGES.items()]
    return "\n".join(lines).rstrip() + "\n"


def build() -> dict[str, str]:
    """Every generated page, keyed by its file name under docs/generated/."""
    return {
        "README.md": _render_index(),
        "courses.md": _render_courses(),
        "launcher.md": _render_launcher(),
        "make-targets.md": _render_make_targets(),
        "motion.md": _render_motion(_load_yaml("motion.yaml")),
        "quests.md": _render_quests(_load_yaml("quests.yaml")),
        "rooms.md": _render_rooms(_load_yaml("rooms.yaml")),
        "runtime-commands.md": _render_runtime_commands(_load_yaml("runtime_commands.yaml")),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated page is stale")
    args = parser.parse_args(argv)
    pages = build()

    if args.check:
        stale = [
            name
            for name, text in pages.items()
            if not (OUT_DIR / name).is_file()
            or (OUT_DIR / name).read_text(encoding="utf-8") != text
        ]
        if stale:
            for name in stale:
                print(f"stale: docs/generated/{name}", file=sys.stderr)
            print(f"❌ docs/generated/ is stale — run `{REGEN}`", file=sys.stderr)
            return 1
        print("✅ docs/generated/ is up to date")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
    print("✅ Generated docs:")
    for name in pages:
        print(f"- docs/generated/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
